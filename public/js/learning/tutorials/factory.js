/**
 * Shared three-path tutorial graph: standard spine, supported recovery, extension.
 * Simulation-specific copy and adapters are passed in; the engine stays generic.
 */

export function adaptiveTutorial({
  id,
  simulationId,
  title,
  objectives,
  adapter,
  intro,
  interface: iface,
  action,
  observe,
  check,
  support,
  retry,
  extension,
  summary,
} = {}) {
  const requiredAction = action.requiredAction || "play";
  return {
    id,
    simulationId,
    version: 1,
    title,
    objectives,
    start: "intro",
    adapter,
    stages: {
      intro: {
        type: "introduction",
        title: intro.title,
        instruction: intro.instruction,
        explanation: intro.explanation,
        highlight: intro.highlight || "scene",
        next: "interface",
      },
      interface: {
        type: "interface",
        title: iface.title,
        instruction: iface.instruction,
        explanation: iface.explanation,
        highlight: iface.highlight,
        next: "action",
      },
      action: {
        type: "guided-action",
        title: action.title,
        instruction: action.instruction,
        explanation: action.explanation,
        highlight: action.highlight,
        requiredAction,
        hints: action.hints || [],
        next: "observe",
        branches: {
          HINT_REQUESTED: "action-support",
          INCOMPLETE_ACTION: "action",
          CORRECT_FIRST_ATTEMPT: "observe",
        },
      },
      "action-support": {
        type: "concept",
        guidance: "supported",
        title: action.supportTitle || "What this action is for",
        instruction: action.supportInstruction,
        explanation: action.supportExplanation,
        highlight: action.highlight,
        next: "action",
      },
      observe: {
        type: "observation",
        title: observe.title,
        instruction: observe.instruction,
        explanation: observe.explanation,
        highlight: observe.highlight,
        next: "concept-check",
      },
      "concept-check": {
        type: "conceptual-question",
        title: check.title,
        instruction: check.instruction || check.question.prompt,
        explanation: check.explanation,
        highlight: check.highlight,
        question: check.question,
        hints: check.hints || [],
        next: "summary",
        branches: {
          CORRECT_FIRST_ATTEMPT: "extension",
          INDEPENDENT_SUCCESS: "extension",
          CONCEPT_MASTERY: "summary",
          CONCEPT_MISUNDERSTANDING: "concept-why",
          REPEATED_ERROR: "concept-why",
          HINT_REQUESTED: "concept-why",
        },
      },
      "concept-why": {
        type: "concept",
        guidance: "supported",
        title: support.title,
        instruction: support.instruction,
        explanation: support.explanation,
        highlight: support.highlight || check.highlight,
        next: "concept-retry",
      },
      "concept-retry": {
        type: "conceptual-question",
        guidance: "supported",
        title: retry.title,
        instruction: retry.instruction || retry.question.prompt,
        explanation: retry.explanation,
        highlight: retry.highlight || check.highlight,
        question: retry.question,
        hints: retry.hints || [],
        next: "summary",
        branches: {
          CORRECT_FIRST_ATTEMPT: "summary",
          CONCEPT_MASTERY: "summary",
          INDEPENDENT_SUCCESS: "summary",
          CONCEPT_MISUNDERSTANDING: "concept-why",
          REPEATED_ERROR: "concept-why",
        },
      },
      extension: {
        type: "application",
        guidance: "extension",
        title: extension.title,
        instruction: extension.instruction,
        explanation: extension.explanation,
        highlight: extension.highlight,
        next: "summary",
      },
      summary: {
        type: "summary",
        title: summary?.title || "Path complete",
        instruction: summary?.instruction || "You finished this guided path on this apparatus.",
        explanation:
          summary?.explanation ||
          "Closing this panel does not reset the lab. How to Use and Guided Lab stay available for the full investigation.",
        next: null,
      },
    },
  };
}
